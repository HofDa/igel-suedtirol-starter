export type MunicipalityId = (typeof southTyrolMunicipalities)[number]['id'];

export const municipalityIds = southTyrolMunicipalities.map((entry) => entry.id) as [
  MunicipalityId,
  ...MunicipalityId[]
];

export function isMunicipalityId(value: string): value is MunicipalityId {
  return (municipalityIds as readonly string[]).includes(value);
}

export function municipalityName(id: MunicipalityId, locale: 'de' | 'it') {
  return southTyrolMunicipalities.find((entry) => entry.id === id)?.[locale] ?? id;
}

// Konservative Hüllbox des Projektgebiets. Sie ist bewusst eine erste
// serverseitige Schranke, nicht der Ersatz für eine spätere PostGIS-Polygonprüfung.
export const SOUTH_TYROL_PROJECT_BOUNDS = {
  south: 46.18,
  west: 10.36,
  north: 47.12,
  east: 12.53
} as const;

export function isWithinSouthTyrolProjectArea(latitude: number, longitude: number) {
  return (
    latitude >= SOUTH_TYROL_PROJECT_BOUNDS.south &&
    latitude <= SOUTH_TYROL_PROJECT_BOUNDS.north &&
    longitude >= SOUTH_TYROL_PROJECT_BOUNDS.west &&
    longitude <= SOUTH_TYROL_PROJECT_BOUNDS.east
  );
}
